#!/usr/bin/env python3
"""Write the pixel order for the opening animation (ui/splash_pixels.slint).

The splash draws the 24 px pixel logo block by block, like a pen stroke: it
starts at the tip of the curl, runs round it and down to the point, then up
the right arm. Each block gets `d`, its position along that stroke (0..1),
measured as the step count of a breadth-first walk through the filled pixels.

Usage: python3 scripts/gen_splash_pixels.py
Needs: Pillow.
"""

from collections import deque
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
LOGO = ROOT / "crates/vanta-app/ui/icons/logo-px24.png"
OUT = ROOT / "crates/vanta-app/ui/splash_pixels.slint"

START = (3, 12)  # tip of the curl (x, y)


def walk(pixels, seeds):
    """Steps from the seeds to every reachable pixel (8-connected)."""
    dist = dict(seeds)
    queue = deque(seeds)
    while queue:
        (x, y), d = queue.popleft()
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                n = (x + dx, y + dy)
                if n in pixels and n not in dist:
                    dist[n] = d + 1
                    queue.append((n, d + 1))
    return dist


def main() -> None:
    alpha = Image.open(LOGO).convert("RGBA").split()[3]
    filled = {(x, y) for y in range(alpha.height) for x in range(alpha.width) if alpha.getpixel((x, y)) > 128}

    # The right arm is drawn last, upwards from where it meets the left stroke.
    right = {(x, y) for x, y in filled if x >= 15 and y <= 14}
    left = filled - right
    d_left = walk(left, [(START, 0)])
    seeds = [(p, d_left[p]) for p in left if any((p[0] + dx, p[1] + dy) in right for dx in (-1, 0, 1) for dy in (-1, 0, 1))]
    end_left = max(d_left.values())
    d_right = walk(right | {p for p, _ in seeds}, [(p, end_left) for p, _ in seeds])
    order = {**d_left, **{p: d for p, d in d_right.items() if p in right}}
    assert set(order) == filled, "every pixel must be reachable"

    top = max(order.values())
    rows = ",\n".join(
        f"        {{ x: {x}, y: {y}, d: {order[(x, y)] / top:.3f} }}" for x, y in sorted(filled, key=lambda p: (order[p], p))
    )
    OUT.write_text(
        "// Generated by scripts/gen_splash_pixels.py. Do not edit.\n"
        "// Blocks of the 24 px logo with their position along the pen stroke.\n\n"
        "export struct SplashPixel { x: int, y: int, d: float }\n\n"
        "export global SplashPixels {\n"
        "    out property <[SplashPixel]> blocks: [\n"
        f"{rows}\n"
        "    ];\n"
        "}\n"
    )
    print(f"{OUT.relative_to(ROOT)}: {len(filled)} blocks")


if __name__ == "__main__":
    main()
